// Crop → Keep area starts with the whole capture selected (node test/crop-keep.mjs [tmpdir]).
import { chromium } from 'playwright';
import fs from 'fs'; import path from 'path'; import http from 'http';
const tmp = path.join(process.argv[2] || 'test/out', `keep-${Date.now()}`);
const ext = path.join(tmp, 'ext');
fs.mkdirSync(tmp, { recursive: true });
fs.cpSync('extension', ext, { recursive: true });
const mf = JSON.parse(fs.readFileSync(path.join(ext, 'manifest.json'))); mf.host_permissions = ['<all_urls>']; fs.writeFileSync(path.join(ext, 'manifest.json'), JSON.stringify(mf));
const server = http.createServer((q, r) => { r.writeHead(200, { 'content-type': 'text/html' }); fs.createReadStream('test/fixtures/long.html').pipe(r); });
await new Promise(r => server.listen(0, r)); const url = `http://127.0.0.1:${server.address().port}/long.html`;
const ctx = await chromium.launchPersistentContext(path.join(tmp, 'profile'), { channel: 'chromium', headless: true, viewport: { width: 1400, height: 900 }, args: [`--disable-extensions-except=${ext}`, `--load-extension=${ext}`] });
let [sw] = ctx.serviceWorkers(); if (!sw) sw = await ctx.waitForEvent('serviceworker');
const page = await ctx.newPage(); await page.goto(url);
const rp = ctx.waitForEvent('page', { predicate: p => p.url().includes('result.html'), timeout: 120000 });
await sw.evaluate(async u => { const [t] = await chrome.tabs.query({ url: u }); return globalThis.ptpCapture(t.id, { scrollDelay: 50 }); }, url);
const v = await rp; await v.waitForFunction(() => window.ptp); await v.setViewportSize({ width: 1400, height: 900 });
await v.click('#cropBtn'); await v.click('[data-crop="keep"]'); await v.waitForTimeout(300);
const handles = await v.$$eval('[data-h^="crop-"]', n => n.map(x => x.dataset.h));
console.log('handles shown on entering Keep area:', handles.join(','));
console.log('stored crop before dragging:', JSON.stringify((await v.evaluate(() => window.ptp.getEdits())).crop));
fs.mkdirSync('test/out/ui', { recursive: true });
await v.screenshot({ path: 'test/out/ui/keep-initial.png' });
const n = await v.$('[data-h="crop-n"]'); const b = await n.boundingBox();
await v.mouse.move(b.x + b.width / 2, b.y + b.height / 2); await v.mouse.down(); await v.mouse.move(b.x + b.width / 2, b.y + 150, { steps: 6 }); await v.mouse.up();
const s = await v.$('[data-h="crop-s"]'); await s.scrollIntoViewIfNeeded(); const bs = await s.boundingBox();
await v.mouse.move(bs.x + bs.width / 2, bs.y + bs.height / 2); await v.mouse.down(); await v.mouse.move(bs.x + bs.width / 2, bs.y - 200, { steps: 6 }); await v.mouse.up();
await v.waitForTimeout(400);
const z = await v.evaluate(() => document.getElementById('doc').getBoundingClientRect().width / 1280);
console.log('zoom', z.toFixed(3), 'crop after dragging top & bottom edges:', JSON.stringify((await v.evaluate(() => window.ptp.getEdits())).crop));
await v.screenshot({ path: 'test/out/ui/keep-bottom.png' });
await v.keyboard.press('Meta+z'); await v.keyboard.press('Meta+z'); await v.waitForTimeout(300);
console.log('after 2× undo:', JSON.stringify((await v.evaluate(() => window.ptp.getEdits())).crop), 'handles:', (await v.$$('[data-h^="crop-"]')).length);
await v.click('#doneEdit'); await v.waitForTimeout(400);
const rec = await v.evaluate(() => window.ptp.getRec());
console.log('stored after Done:', JSON.stringify(rec.edits?.crop ?? null));
await ctx.close(); server.close();
